/* ============================================================
   SCRIPT : Crear tablas de trazabilidad OmniStack
   SCHEMA : GPF_OMNISTACK
   TABLAS :
     IN_OMNI_LOGS_APP       - Auditoria de peticiones al API
     IN_OMNI_LOGS_WS_EXT    - Log de llamadas a proveedores externos
     IN_OMNI_REGISTRO_TRX   - Registro de transacciones completadas

   EJECUTAR conectado como GPF_OMNISTACK (o con DBA)
   ============================================================ */

-- ============================================================
-- 1) IN_OMNI_LOGS_APP
-- ============================================================
CREATE TABLE GPF_OMNISTACK.IN_OMNI_LOGS_APP (
  CODIGO             NUMBER(18)     NOT NULL,
  UUID               VARCHAR2(200),
  REQUEST            CLOB,
  RESPONSE           CLOB,
  USUARIO            VARCHAR2(100),
  FECHA_REGISTRO     DATE,
  MENSAJE            VARCHAR2(2000),
  PROVEEDOR          VARCHAR2(100),
  CAPABILITY         VARCHAR2(50),
  CANAL              VARCHAR2(50),
  CADENA             NUMBER(10),
  FARMACIA           NUMBER(10),
  NOMBRE_FARMACIA    VARCHAR2(200),
  POS                VARCHAR2(20),
  URL                VARCHAR2(500),
  METODO             VARCHAR2(20),
  HTTP_STATUS        NUMBER(5),
  ES_ERROR           CHAR(1),
  COD_ERROR          VARCHAR2(200),
  MSG_ERROR          VARCHAR2(2000),
  CP_VAR1            VARCHAR2(1500),
  CP_VAR2            VARCHAR2(1500),
  CP_VAR3            VARCHAR2(1500),
  CP_NUMBER1         NUMBER,
  CP_NUMBER2         NUMBER,
  CP_DATE1           DATE,
  CP_DATE2           DATE,
  CONSTRAINT PK_IN_OMNI_LOGS_APP   PRIMARY KEY (CODIGO),
  CONSTRAINT CK_IN_OMNI_LOGS_APP_ERR CHECK (ES_ERROR IN ('S','N'))
);

CREATE SEQUENCE GPF_OMNISTACK.SEQ_IN_OMNI_LOGS_APP
  START WITH 1 INCREMENT BY 1 CACHE 500 NOCYCLE;

CREATE OR REPLACE TRIGGER GPF_OMNISTACK.TRG_IN_OMNI_LOGS_APP_BI
BEFORE INSERT ON GPF_OMNISTACK.IN_OMNI_LOGS_APP
FOR EACH ROW
BEGIN
  IF :NEW.CODIGO IS NULL THEN
    SELECT GPF_OMNISTACK.SEQ_IN_OMNI_LOGS_APP.NEXTVAL INTO :NEW.CODIGO FROM DUAL;
  END IF;
  IF :NEW.FECHA_REGISTRO IS NULL THEN
    :NEW.FECHA_REGISTRO := SYSDATE;
  END IF;
END;
/

CREATE INDEX GPF_OMNISTACK.IX_IN_OMNI_LOGS_APP_UUID  ON GPF_OMNISTACK.IN_OMNI_LOGS_APP (UUID);
CREATE INDEX GPF_OMNISTACK.IX_IN_OMNI_LOGS_APP_FECHA ON GPF_OMNISTACK.IN_OMNI_LOGS_APP (FECHA_REGISTRO);
CREATE INDEX GPF_OMNISTACK.IX_IN_OMNI_LOGS_APP_PROV  ON GPF_OMNISTACK.IN_OMNI_LOGS_APP (PROVEEDOR, FECHA_REGISTRO);
CREATE INDEX GPF_OMNISTACK.IX_IN_OMNI_LOGS_APP_CAP   ON GPF_OMNISTACK.IN_OMNI_LOGS_APP (CAPABILITY, FECHA_REGISTRO);

